package co.edu.corhuila.marketagri.workflow.adapter.out.http;

import static org.assertj.core.api.Assertions.assertThat;

import au.com.dius.pact.consumer.MockServer;
import au.com.dius.pact.consumer.dsl.PactBuilder;
import au.com.dius.pact.consumer.junit5.PactConsumerTestExt;
import au.com.dius.pact.consumer.junit5.PactTestFor;
import au.com.dius.pact.core.model.annotations.Pact;
import au.com.dius.pact.core.model.V4Pact;
import co.edu.corhuila.marketagri.workflow.application.port.out.StepCall;
import co.edu.corhuila.marketagri.workflow.domain.model.Conversation;
import co.edu.corhuila.marketagri.workflow.domain.model.PurchaseMethod;
import co.edu.corhuila.marketagri.workflow.domain.model.Quantity;
import co.edu.corhuila.marketagri.workflow.domain.model.Reservation;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.math.BigDecimal;
import java.net.URI;
import java.time.Duration;
import java.util.Map;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.slf4j.MDC;

/**
 * The contracts are generated by the real outbound adapters, not copied from OpenAPI. They freeze
 * the three calls that workflow makes: catalog I-03/I-04 and transactions I-06.
 */
@ExtendWith(PactConsumerTestExt.class)
class WorkflowConsumerPactTest {

    private static final UUID PRODUCT_ID = UUID.fromString("11111111-1111-1111-1111-111111111111");
    private static final UUID TRANSACTION_ID = UUID.fromString("22222222-2222-2222-2222-222222222222");
    private static final UUID CONVERSATION_ID = UUID.fromString("33333333-3333-3333-3333-333333333333");
    private static final UUID BUYER_ID = UUID.fromString("44444444-4444-4444-4444-444444444444");
    private static final UUID PRODUCER_ID = UUID.fromString("55555555-5555-5555-5555-555555555555");
    private static final String TOKEN = "workflow-service-token";
    private static final String CORRELATION_ID = "e6-workflow-contract";
    private static final ObjectMapper JSON = new ObjectMapper();
    private static final ServiceCaller CALLER = new ServiceCaller(TOKEN, Duration.ofSeconds(3), 1,
            Duration.ofMillis(200), ServiceCallerTest.CEILING, duration -> { });

    @BeforeEach
    void addTheCorrelationIdExpectedByEachContract() {
        MDC.put("correlationId", CORRELATION_ID);
    }

    @AfterEach
    void clearTheCorrelationId() {
        MDC.clear();
    }

    @Pact(provider = "catalog-api", consumer = "workflow")
    public V4Pact reserveStock(PactBuilder builder) {
        return builder.given("an active product has enough stock")
                .expectsToReceiveHttpInteraction("I-03 reserve stock for the checkout", interaction -> interaction
                        .withRequest(request -> request.path("/internal/v1/catalog/products/" + PRODUCT_ID + "/reservations")
                                .method("POST").headers(requestHeaders("saga:reserve-stock"))
                                .body("{\"transactionId\":\"" + TRANSACTION_ID + "\",\"quantity\":2.50}"))
                        .willRespondWith(response -> response.status(201)
                                .headers(Map.of("Content-Type", "application/json")).body(reservationJson())))
                .toPact();
    }

    @Test
    @PactTestFor(pactMethod = "reserveStock")
    void reservesStockWithCatalogsI03Contract(MockServer server) {
        StepCall<?> result = new HttpStockReservations(CALLER, URI.create(server.getUrl()), JSON)
                .reserve("saga:reserve-stock", PRODUCT_ID, TRANSACTION_ID, new Quantity(new BigDecimal("2.50")));

        assertThat(result).isInstanceOf(StepCall.Done.class);
    }

    @Pact(provider = "catalog-api", consumer = "workflow")
    public V4Pact releaseStock(PactBuilder builder) {
        return builder.given("a reservation may exist or may already be released")
                .expectsToReceiveHttpInteraction("I-04 release the checkout reservation", interaction -> interaction
                        .withRequest(request -> request.path("/internal/v1/catalog/reservations/" + TRANSACTION_ID)
                                .method("DELETE").headers(requestHeaders(null)))
                        .willRespondWith(response -> response.status(204)))
                .toPact();
    }

    @Test
    @PactTestFor(pactMethod = "releaseStock")
    void releasesStockWithCatalogsI04Contract(MockServer server) {
        assertThat(new HttpStockReservations(CALLER, URI.create(server.getUrl()), JSON).release(TRANSACTION_ID)).isTrue();
    }

    @Pact(provider = "transactions-api", consumer = "workflow")
    public V4Pact createPayment(PactBuilder builder) {
        return builder.given("the checkout does not have a payment yet")
                .expectsToReceiveHttpInteraction("I-06 create the checkout payment", interaction -> interaction
                        .withRequest(request -> request.path("/internal/v1/transactions").method("POST")
                                .headers(requestHeaders("saga:create-payment")).body(paymentRequestJson()))
                        .willRespondWith(response -> response.status(201)
                                .headers(Map.of("Content-Type", "application/json"))
                                .body("{\"transaction\":{\"id\":\"" + TRANSACTION_ID
                                        + "\",\"status\":\"PENDING\",\"amountCents\":21250000},\"checkoutUrl\":"
                                        + "\"https://checkout.wompi.co/p/?reference=" + TRANSACTION_ID + "\"}")))
                .toPact();
    }

    @Test
    @PactTestFor(pactMethod = "createPayment")
    void createsPaymentWithTransactionsI06Contract(MockServer server) {
        var result = new HttpPaymentCreator(CALLER, URI.create(server.getUrl()), JSON).create("saga:create-payment", TRANSACTION_ID,
                new Conversation(CONVERSATION_ID, PRODUCT_ID, "Café", BUYER_ID, "Ana", PRODUCER_ID, "Luis",
                        PurchaseMethod.PLATFORM), reservation());

        assertThat(result).isInstanceOf(StepCall.Done.class);
    }

    private static Reservation reservation() {
        return new Reservation(TRANSACTION_ID, PRODUCT_ID, "Café", PRODUCER_ID, new BigDecimal("2.50"), "KILOGRAMO",
                8_500_000L);
    }

    private static Map<String, Object> requestHeaders(String idempotencyKey) {
        Map<String, Object> headers = new java.util.LinkedHashMap<>();
        headers.put("Authorization", "Bearer " + TOKEN);
        headers.put("X-Correlation-Id", CORRELATION_ID);
        if (idempotencyKey != null) {
            headers.put("Idempotency-Key", idempotencyKey);
            headers.put("Content-Type", "application/json");
        }
        return headers;
    }

    private static String reservationJson() {
        return "{\"transactionId\":\"" + TRANSACTION_ID + "\",\"productId\":\"" + PRODUCT_ID + "\","
                + "\"productName\":\"Café\",\"producerId\":\"" + PRODUCER_ID + "\",\"quantity\":2.50,"
                + "\"unit\":\"KILOGRAMO\",\"unitPriceCents\":8500000,\"currency\":\"COP\","
                + "\"remainingQuantity\":7.50,\"createdAt\":\"2026-11-10T00:00:00Z\"}";
    }

    private static String paymentRequestJson() {
        return "{\"transactionId\":\"" + TRANSACTION_ID + "\",\"conversationId\":\"" + CONVERSATION_ID + "\","
                + "\"buyerId\":\"" + BUYER_ID + "\",\"buyerName\":\"Ana\",\"producerId\":\"" + PRODUCER_ID
                + "\",\"producerName\":\"Luis\",\"productId\":\"" + PRODUCT_ID + "\",\"productName\":\"Café\","
                + "\"quantity\":2.50,\"unit\":\"KILOGRAMO\",\"unitPriceCents\":8500000}";
    }
}
